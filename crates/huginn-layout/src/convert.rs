fn breadth_min(b: TrackBreadth) -> tf::MinTrackSizingFunction {
    match b {
        TrackBreadth::Length(LengthPercentage::Px(px)) => tf::MinTrackSizingFunction::length(px),
        TrackBreadth::Length(LengthPercentage::Percent(p)) => {
            tf::MinTrackSizingFunction::percent(p / 100.0)
        }
        TrackBreadth::Length(LengthPercentage::Calc(c)) if c.percent == 0.0 => {
            tf::MinTrackSizingFunction::length(c.px)
        }
        TrackBreadth::Length(LengthPercentage::Calc(c)) => {
            tf::MinTrackSizingFunction::calc(calc_handle(c))
        }
        // A flexible minimum is invalid CSS; `auto` is the closest.
        TrackBreadth::Fr(_) | TrackBreadth::Auto => tf::MinTrackSizingFunction::auto(),
        TrackBreadth::MinContent => tf::MinTrackSizingFunction::min_content(),
        TrackBreadth::MaxContent => tf::MinTrackSizingFunction::max_content(),
    }
}

fn breadth_max(b: TrackBreadth) -> tf::MaxTrackSizingFunction {
    match b {
        TrackBreadth::Length(LengthPercentage::Px(px)) => tf::MaxTrackSizingFunction::length(px),
        TrackBreadth::Length(LengthPercentage::Percent(p)) => {
            tf::MaxTrackSizingFunction::percent(p / 100.0)
        }
        TrackBreadth::Length(LengthPercentage::Calc(c)) if c.percent == 0.0 => {
            tf::MaxTrackSizingFunction::length(c.px)
        }
        TrackBreadth::Length(LengthPercentage::Calc(c)) => {
            tf::MaxTrackSizingFunction::calc(calc_handle(c))
        }
        TrackBreadth::Fr(f) => tf::MaxTrackSizingFunction::fr(f),
        TrackBreadth::Auto => tf::MaxTrackSizingFunction::auto(),
        TrackBreadth::MinContent => tf::MaxTrackSizingFunction::min_content(),
        TrackBreadth::MaxContent => tf::MaxTrackSizingFunction::max_content(),
    }
}

fn track(t: TrackSize) -> taffy::TrackSizingFunction {
    match t {
        TrackSize::Breadth(b) => taffy::MinMax {
            min: breadth_min(b),
            max: breadth_max(b),
        },
        TrackSize::MinMax(a, b) => taffy::MinMax {
            min: breadth_min(a),
            max: breadth_max(b),
        },
        TrackSize::FitContent(lp) => taffy::MinMax {
            min: tf::MinTrackSizingFunction::auto(),
            max: match lp {
                LengthPercentage::Percent(p) => {
                    tf::MaxTrackSizingFunction::fit_content_percent(p / 100.0)
                }
                other => tf::MaxTrackSizingFunction::fit_content_px(other.resolve(None)),
            },
        },
    }
}

/// `grid-template-columns`/`-rows` -> Taffy tracks and line names.
fn template(tracks: &[GridTrack]) -> (Vec<taffy::GridTemplateComponent<String>>, Vec<Vec<String>>) {
    let mut out = Vec::new();
    let mut names: Vec<Vec<String>> = vec![Vec::new()];
    let mut any_name = false;
    for t in tracks {
        match t {
            GridTrack::LineNames(n) => {
                any_name = true;
                names
                    .last_mut()
                    .expect("one entry per line")
                    .extend(n.iter().map(|s| s.to_string()));
            }
            GridTrack::Size(s) => {
                out.push(taffy::GridTemplateComponent::Single(track(*s)));
                names.push(Vec::new());
            }
            GridTrack::Repeat(count, sizes) => {
                out.push(taffy::GridTemplateComponent::Repeat(
                    taffy::GridTemplateRepetition {
                        count: match count {
                            GridRepeat::Count(n) => taffy::RepetitionCount::Count(*n),
                            GridRepeat::AutoFill => taffy::RepetitionCount::AutoFill,
                            GridRepeat::AutoFit => taffy::RepetitionCount::AutoFit,
                        },
                        tracks: sizes.iter().map(|s| track(*s)).collect(),
                        line_names: Vec::new(),
                    },
                ));
                names.push(Vec::new());
            }
        }
    }
    if !any_name {
        names.clear();
    }
    (out, names)
}

fn placement(l: &GridLine) -> taffy::GridPlacement<String> {
    match l {
        GridLine::Auto => taffy::GridPlacement::Auto,
        GridLine::Line(n) => taffy::style_helpers::line(*n),
        GridLine::Span(n) => taffy::GridPlacement::Span(*n),
        GridLine::Named(name) => taffy::GridPlacement::NamedLine(name.to_string(), 0),
    }
}

fn apply_grid(s: &ComputedStyle, st: &mut crate::tree::TStyle) {
    if let Some(cols) = &s.grid_template_columns {
        let (t, n) = template(cols);
        st.grid_template_columns = t;
        st.grid_template_column_names = n;
    }
    if let Some(rows) = &s.grid_template_rows {
        let (t, n) = template(rows);
        st.grid_template_rows = t;
        st.grid_template_row_names = n;
    }
    if let Some(areas) = &s.grid_template_areas {
        let rows = areas
            .iter()
            .map(|a| a.row_end.saturating_sub(1))
            .max()
            .unwrap_or(0);
        let cols = areas
            .iter()
            .map(|a| a.column_end.saturating_sub(1))
            .max()
            .unwrap_or(0);
        st.grid_template_areas = Some(taffy::GridTemplateAreas {
            areas: areas
                .iter()
                .map(|a| taffy::GridTemplateArea {
                    name: a.name.to_string(),
                    row_start: a.row_start,
                    row_end: a.row_end,
                    column_start: a.column_start,
                    column_end: a.column_end,
                })
                .collect(),
            row_count: rows,
            column_count: cols,
        });
    }
    if let Some(a) = &s.grid_auto_columns {
        st.grid_auto_columns = a.iter().map(|t| track(*t)).collect();
    }
    if let Some(a) = &s.grid_auto_rows {
        st.grid_auto_rows = a.iter().map(|t| track(*t)).collect();
    }
    st.grid_auto_flow = match s.grid_auto_flow {
        huginn_style::GridAutoFlow::Row => taffy::GridAutoFlow::Row,
        huginn_style::GridAutoFlow::Column => taffy::GridAutoFlow::Column,
        huginn_style::GridAutoFlow::RowDense => taffy::GridAutoFlow::RowDense,
        huginn_style::GridAutoFlow::ColumnDense => taffy::GridAutoFlow::ColumnDense,
    };
    st.grid_column = taffy::Line {
        start: placement(&s.grid_column.0),
        end: placement(&s.grid_column.1),
    };
    st.grid_row = taffy::Line {
        start: placement(&s.grid_row.0),
        end: placement(&s.grid_row.1),
    };
    if let Some(a) = align_items(s.justify_items) {
        st.justify_items = a;
    }
    st.justify_self = align_items(s.justify_self);
}
