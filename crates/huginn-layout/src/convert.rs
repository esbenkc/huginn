use std::borrow::Cow;

use huginn_style::{
    Alignment, BoxSizing, CalcLength, Clear, Color, ComputedStyle, Display, FlexDirection,
    FlexWrap, Float, FontStyle, GridLine, GridRepeat, GridTrack, LengthPercentage,
    LengthPercentageAuto, Overflow, Position, TextAlign, TrackBreadth, TrackSize, WhiteSpace,
};
use taffy::prelude as tf;

use crate::inline::Brush;

/// `calc(px + percent%)` as a Taffy calc handle. The handle is not a pointer:
/// the high 32 bits hold `px`, the low 32 bits hold `percent` with its 3 low
/// mantissa bits cleared (Taffy's tag bits). [`resolve_calc`] decodes it.
fn calc_handle(c: CalcLength) -> *const () {
    let bits = ((c.px.to_bits() as u64) << 32) | (c.percent.to_bits() & !0b111) as u64;
    std::ptr::without_provenance(bits as usize)
}

/// Resolve a handle from [`calc_handle`] against `basis` (the percentage basis).
pub(crate) fn resolve_calc(handle: *const (), basis: f32) -> f32 {
    let bits = handle.addr() as u64;
    f32::from_bits((bits >> 32) as u32) + basis * f32::from_bits(bits as u32) / 100.0
}

fn lp(v: LengthPercentage) -> tf::LengthPercentage {
    match v {
        LengthPercentage::Px(px) => tf::LengthPercentage::length(px),
        LengthPercentage::Percent(p) => tf::LengthPercentage::percent(p / 100.0),
        LengthPercentage::Calc(c) if c.percent == 0.0 => tf::LengthPercentage::length(c.px),
        LengthPercentage::Calc(c) if c.px == 0.0 => {
            tf::LengthPercentage::percent(c.percent / 100.0)
        }
        LengthPercentage::Calc(c) => tf::LengthPercentage::calc(calc_handle(c)),
    }
}

fn lpa(v: LengthPercentageAuto) -> tf::LengthPercentageAuto {
    match v {
        LengthPercentageAuto::Auto => tf::LengthPercentageAuto::auto(),
        LengthPercentageAuto::Px(px) => tf::LengthPercentageAuto::length(px),
        LengthPercentageAuto::Percent(p) => tf::LengthPercentageAuto::percent(p / 100.0),
        LengthPercentageAuto::Calc(c) => lp(LengthPercentage::Calc(c)).into(),
    }
}

fn dim(v: LengthPercentageAuto) -> tf::Dimension {
    match v {
        LengthPercentageAuto::Auto => tf::Dimension::auto(),
        LengthPercentageAuto::Px(px) => tf::Dimension::length(px),
        LengthPercentageAuto::Percent(p) => tf::Dimension::percent(p / 100.0),
        LengthPercentageAuto::Calc(c) => lp(LengthPercentage::Calc(c)).into(),
    }
}

fn rect<T: Copy, U>(e: huginn_style::Edges<T>, f: impl Fn(T) -> U) -> taffy::Rect<U> {
    taffy::Rect {
        left: f(e.left),
        right: f(e.right),
        top: f(e.top),
        bottom: f(e.bottom),
    }
}

fn align_items(a: Alignment) -> Option<taffy::AlignItems> {
    Some(match a {
        Alignment::Normal => return None,
        Alignment::Start | Alignment::Left => taffy::AlignItems::START,
        Alignment::End | Alignment::Right => taffy::AlignItems::END,
        Alignment::FlexStart => taffy::AlignItems::FLEX_START,
        Alignment::FlexEnd => taffy::AlignItems::FLEX_END,
        Alignment::Center => taffy::AlignItems::CENTER,
        Alignment::Baseline => taffy::AlignItems::BASELINE,
        Alignment::Stretch
        | Alignment::SpaceBetween
        | Alignment::SpaceAround
        | Alignment::SpaceEvenly => taffy::AlignItems::STRETCH,
    })
}

fn align_content(a: Alignment) -> taffy::AlignContent {
    match a {
        Alignment::Normal => taffy::AlignContent::NORMAL,
        Alignment::Start | Alignment::Left => taffy::AlignContent::START,
        Alignment::End | Alignment::Right => taffy::AlignContent::END,
        Alignment::FlexStart | Alignment::Baseline => taffy::AlignContent::FLEX_START,
        Alignment::FlexEnd => taffy::AlignContent::FLEX_END,
        Alignment::Center => taffy::AlignContent::CENTER,
        Alignment::Stretch => taffy::AlignContent::STRETCH,
        Alignment::SpaceBetween => taffy::AlignContent::SPACE_BETWEEN,
        Alignment::SpaceAround => taffy::AlignContent::SPACE_AROUND,
        Alignment::SpaceEvenly => taffy::AlignContent::SPACE_EVENLY,
    }
}

fn overflow(o: Overflow) -> taffy::Overflow {
    match o {
        Overflow::Visible => taffy::Overflow::Visible,
        Overflow::Clip => taffy::Overflow::Clip,
        Overflow::Hidden => taffy::Overflow::Hidden,
        // No scrollbars in headless rendering; reserve no space.
        Overflow::Scroll | Overflow::Auto => taffy::Overflow::Hidden,
    }
}

/// Taffy style for a box generated by `s`. `leaf` boxes (text, images) are
/// laid out as Taffy leaves with a measure function.
pub(crate) fn taffy_style(s: &ComputedStyle, leaf: bool) -> crate::tree::TStyle {
    let display = if leaf {
        tf::Display::Block
    } else {
        match s.display {
            // A table-row outside a table: lay its cells out in a row.
            Display::Flex | Display::InlineFlex | Display::TableRow => tf::Display::Flex,
            Display::Grid | Display::InlineGrid => tf::Display::Grid,
            Display::FlowRoot
            | Display::InlineBlock
            | Display::TableCell
            | Display::TableCaption => tf::Display::FlowRoot,
            Display::None => tf::Display::None,
            _ => tf::Display::Block,
        }
    };
    let mut st = crate::tree::TStyle {
        display,
        box_sizing: match s.box_sizing {
            BoxSizing::BorderBox => taffy::BoxSizing::BorderBox,
            BoxSizing::ContentBox => taffy::BoxSizing::ContentBox,
        },
        // Sticky: at scroll 0 a sticky box sits at its static position.
        position: match s.position {
            Position::Absolute => taffy::Position::Absolute,
            Position::Fixed => taffy::Position::Fixed,
            Position::Relative => taffy::Position::Relative,
            Position::Sticky => taffy::Position::Sticky,
            Position::Static => taffy::Position::Static,
        },
        inset: if s.position == Position::Static {
            taffy::Rect {
                left: tf::LengthPercentageAuto::auto(),
                right: tf::LengthPercentageAuto::auto(),
                top: tf::LengthPercentageAuto::auto(),
                bottom: tf::LengthPercentageAuto::auto(),
            }
        } else {
            rect(s.inset, lpa)
        },
        overflow: taffy::Point {
            x: overflow(s.overflow_x),
            y: overflow(s.overflow_y),
        },
        scrollbar_width: 0.0,
        size: tf::Size {
            width: dim(s.width),
            height: dim(s.height),
        },
        min_size: tf::Size {
            width: lpa(s.min_width),
            height: lpa(s.min_height),
        },
        max_size: tf::Size {
            width: lpa(s.max_width),
            height: lpa(s.max_height),
        },
        aspect_ratio: s.aspect_ratio,
        margin: rect(s.margin, lpa),
        padding: rect(s.padding, lp),
        border: rect(s.border_width, tf::LengthPercentage::length),
        flex_direction: match s.flex_direction {
            FlexDirection::Row => taffy::FlexDirection::Row,
            FlexDirection::RowReverse => taffy::FlexDirection::RowReverse,
            FlexDirection::Column => taffy::FlexDirection::Column,
            FlexDirection::ColumnReverse => taffy::FlexDirection::ColumnReverse,
        },
        flex_wrap: match s.flex_wrap {
            FlexWrap::NoWrap => taffy::FlexWrap::NoWrap,
            FlexWrap::Wrap => taffy::FlexWrap::Wrap,
            FlexWrap::WrapReverse => taffy::FlexWrap::WrapReverse,
        },
        flex_grow: s.flex_grow,
        flex_shrink: s.flex_shrink,
        flex_basis: dim(s.flex_basis),
        justify_content: align_content(s.justify_content),
        align_content: align_content(s.align_content),
        align_self: align_items(s.align_self),
        gap: tf::Size {
            width: lp(s.column_gap),
            height: lp(s.row_gap),
        },
        float: match s.float {
            Float::None => taffy::Float::None,
            Float::Left => taffy::Float::Left,
            Float::Right => taffy::Float::Right,
        },
        clear: match s.clear {
            Clear::None => taffy::Clear::None,
            Clear::Left => taffy::Clear::Left,
            Clear::Right => taffy::Clear::Right,
            Clear::Both => taffy::Clear::Both,
        },
        // `-webkit-*` alignment also aligns block children (`<center>`).
        text_align: match s.text_align {
            TextAlign::WebkitLeft => taffy::TextAlign::LegacyLeft,
            TextAlign::WebkitRight => taffy::TextAlign::LegacyRight,
            TextAlign::WebkitCenter => taffy::TextAlign::LegacyCenter,
            _ => taffy::TextAlign::Auto,
        },
        ..Default::default()
    };
    if let Some(a) = align_items(s.align_items) {
        st.align_items = a;
    }
    apply_grid(s, &mut st);
    st
}

/// Parley text style for an element or anonymous box with style `s`.
/// `decor` carries text decorations propagated from ancestors; `family` is
/// `s.font_family` resolved by [`crate::fonts::Fonts::family_list`] and
/// `line_height` comes from [`crate::fonts::Fonts::line_height`]. `span`
/// goes into the brush; `root` is true for the IFC's own style.
/// `variations` is [`optical_sizing`] of `s`.
#[allow(clippy::too_many_arguments)]
pub(crate) fn text_style<'a>(
    s: &ComputedStyle,
    decor: &Decor,
    family: &'a [parley::FontFamilyName<'static>],
    line_height: parley::LineHeight,
    span: u32,
    root: bool,
    variations: &'a [parley::FontVariation],
) -> parley::TextStyle<'a, 'a, Brush> {
    let brush = |color: Color| Brush { color, span };
    parley::TextStyle {
        font_family: parley::FontFamily::List(Cow::Borrowed(family)),
        font_size: s.font_size,
        font_variations: parley::FontVariations::List(Cow::Borrowed(variations)),
        // `font-feature-settings` (e.g. Inter's `cv11` single-storey a).
        font_features: match &s.font_feature_settings {
            Some(list) => parley::FontFeatures::List(Cow::Owned(
                list.iter()
                    .map(|f| {
                        parley::FontFeature::new(
                            parley::setting::Tag::new(&f.tag),
                            f.value.min(u16::MAX as u32) as u16,
                        )
                    })
                    .collect(),
            )),
            None => parley::FontFeatures::empty(),
        },
        font_weight: parley::FontWeight::new(s.font_weight),
        font_style: match s.font_style {
            FontStyle::Normal => parley::FontStyle::Normal,
            FontStyle::Italic => parley::FontStyle::Italic,
            FontStyle::Oblique => parley::FontStyle::Oblique(None),
        },
        brush: brush(s.color),
        has_underline: decor.underline.is_some(),
        underline_brush: decor.underline.map(brush),
        has_strikethrough: decor.line_through.is_some(),
        strikethrough_brush: decor.line_through.map(brush),
        line_height,
        vertical_align: if root {
            parley::VerticalAlign::BASELINE
        } else {
            crate::inline::vertical_align(s.vertical_align)
        },
        letter_spacing: s.letter_spacing,
        word_spacing: s.word_spacing,
        text_wrap_mode: match s.white_space {
            WhiteSpace::Nowrap | WhiteSpace::Pre => parley::TextWrapMode::NoWrap,
            _ => parley::TextWrapMode::Wrap,
        },
        white_space_collapse: match s.white_space {
            WhiteSpace::Normal | WhiteSpace::Nowrap => parley::WhiteSpaceCollapse::Collapse,
            WhiteSpace::Pre | WhiteSpace::PreWrap => parley::WhiteSpaceCollapse::Preserve,
            WhiteSpace::PreLine => parley::WhiteSpaceCollapse::PreserveBreaks,
            WhiteSpace::BreakSpaces => parley::WhiteSpaceCollapse::BreakSpaces,
        },
        ..Default::default()
    }
}

/// `font-optical-sizing: auto` (the initial value): fonts with an `opsz`
/// axis use the font size in CSS px as the optical size, as Chrome does.
/// Fonts without the axis ignore it.
pub(crate) fn optical_sizing(s: &ComputedStyle) -> [parley::FontVariation; 1] {
    [parley::FontVariation::new(
        parley::setting::Tag::new(b"opsz"),
        s.font_size,
    )]
}

/// `opacity` on an inline element: Chrome paints the element as one group.
/// For its text and text decorations, scaling their alpha gives the same
/// pixels unless glyphs overlap.
pub(crate) fn fade(ts: &mut parley::TextStyle<'_, '_, Brush>, opacity: f32) {
    let scale = |b: &mut Brush| b.color.a = (f32::from(b.color.a) * opacity).round() as u8;
    scale(&mut ts.brush);
    for b in [&mut ts.underline_brush, &mut ts.strikethrough_brush]
        .into_iter()
        .flatten()
    {
        scale(b);
    }
}

pub(crate) fn text_align(a: TextAlign) -> parley::Alignment {
    match a {
        TextAlign::Start => parley::Alignment::Start,
        TextAlign::End => parley::Alignment::End,
        TextAlign::Left => parley::Alignment::Left,
        TextAlign::Right => parley::Alignment::Right,
        TextAlign::Center | TextAlign::WebkitCenter => parley::Alignment::Center,
        TextAlign::Justify => parley::Alignment::Justify,
        TextAlign::WebkitLeft => parley::Alignment::Left,
        TextAlign::WebkitRight => parley::Alignment::Right,
    }
}

/// Text decorations in effect, propagated from decorating ancestors.
#[derive(Copy, Clone, Debug, Default, PartialEq)]
pub(crate) struct Decor {
    pub underline: Option<Color>,
    pub line_through: Option<Color>,
}

impl Decor {
    /// Decorations for descendants of an element with style `s`.
    pub fn extend(self, s: &ComputedStyle) -> Decor {
        let line = s.text_decoration_line;
        Decor {
            underline: if line.underline {
                Some(s.text_decoration_color)
            } else {
                self.underline
            },
            line_through: if line.line_through {
                Some(s.text_decoration_color)
            } else {
                self.line_through
            },
        }
    }
}

